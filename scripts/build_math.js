// Typeset every formula used in the film (TeX → self-contained SVG via MathJax) into math.js.
// The overlay draws these instead of text, so no "_" or "^" ever appears on screen.
// Usage: node scripts/build_math.js   (run by build.js)
const fs = require('fs'), path = require('path');
const { mathjax } = require('mathjax-full/js/mathjax.js');
const { TeX } = require('mathjax-full/js/input/tex.js');
const { SVG } = require('mathjax-full/js/output/svg.js');
const { liteAdaptor } = require('mathjax-full/js/adaptors/liteAdaptor.js');
const { RegisterHTMLHandler } = require('mathjax-full/js/handlers/html.js');
const { AllPackages } = require('mathjax-full/js/input/tex/AllPackages.js');

const FORMULAS = {
  vtheta: 'v_\\theta',
  Ahat: '\\hat{A}',
  KAhat: 'K(\\hat{A})',
  EKAhat: 'E\\big(K(\\hat{A})\\big)',
  guided: 'v_\\theta - \\lambda\\,\\nabla E',
  eikonal: 'S(x)\\,\\lVert \\nabla T(x) \\rVert = 1',
  taylor: 'E(A + \\Delta A) \\approx E(A) + \\nabla E(A)^{\\top} \\Delta A',
  energy1: 'E(A;\\, g, c) \\,=\\, E_{\\mathrm{geo}}(A;\\, c)',
  energy2: '+\\; \\ell\\big(F_\\theta(h, A);\\, g, c\\big)',
  Ftheta: 'F_\\theta',
  gc: 'g,\\, c'
};

const adaptor = liteAdaptor(); RegisterHTMLHandler(adaptor);
const doc = mathjax.document('', { InputJax: new TeX({ packages: AllPackages }), OutputJax: new SVG({ fontCache: 'none' }) });
const out = {};
for (const [k, tex] of Object.entries(FORMULAS)) {
  let svg = adaptor.innerHTML(doc.convert(tex, { display: false, em: 16, ex: 8, containerWidth: 1280 }));
  const vb = svg.match(/viewBox="([-\d.]+) ([-\d.]+) ([-\d.]+) ([-\d.]+)"/).slice(1).map(Number);
  // intrinsic size at a 100 px em so the browser rasterizes crisply when scaled down
  svg = svg.replace(/currentColor/g, '#FFFFFF').replace(/ style="[^"]*"/, '')
    .replace(/ width="[^"]*"/, ` width="${(vb[2] / 10).toFixed(1)}px"`).replace(/ height="[^"]*"/, ` height="${(vb[3] / 10).toFixed(1)}px"`);
  if (!/xmlns=/.test(svg)) svg = svg.replace('<svg', '<svg xmlns="http://www.w3.org/2000/svg"');
  out[k] = { tex, svg, vb }; // vb in 1/1000 em; baseline at y = 0
}
const js = `/* math.js — generated by scripts/build_math.js (MathJax ${require('mathjax-full/package.json').version}); do not edit. */
(function (root) { root.MGMath = ${JSON.stringify(out)}; })(typeof self !== 'undefined' ? self : this);
`;
fs.writeFileSync(path.join(__dirname, '..', 'math.js'), js);
console.log('typeset', Object.keys(out).length, 'formulas →', js.length, 'bytes');
